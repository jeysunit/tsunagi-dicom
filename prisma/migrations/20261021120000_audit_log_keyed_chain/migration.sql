-- 監査の記録のつなぎを、鍵つきの MAC（HMAC-SHA256）にする（docs/adr/0001-audit-chain-mac.md）。
-- keyId：その行の hash を計算した鍵の印（鍵から導いた 16 桁。鍵そのものではない）。
-- この版より前の行は keyId が空で、hash は鍵の無い SHA-256 のまま（書き換えない。追記だけの決まりのため）。
-- この版からの行は keyId を持ち、hash は SESSION_SECRET から HKDF で導いた専用の鍵の HMAC-SHA256 になる。
--
-- 20261018000000_audit_log の注釈の「ファイルを直に書き換えられたときは、つなぎの確かめで見つける」は、
-- 鍵の無い SHA-256 のつなぎでは成り立たなかった（ファイルに書ける者は、trigger を外して行を書き換え、
-- hash を作り直せる）。その注釈は、適用済みの migration を書き換えないため、そのまま残す。今の保証は次のとおり：
-- - keyId のある行：鍵（SESSION_SECRET）を持たない者が書き換え・差し込み・途中の削除をすると、確かめで見つかる。
-- - 末尾の削除（切り詰め）と、鍵を持つ者による作り直しは、つなぎだけでは見つからない。データベースの外に書き出した
--   先頭の控え（AUDIT_ANCHOR_FILE とコンテナのログ）と照らして見つける。
-- AlterTable
ALTER TABLE "AuditLog" ADD COLUMN "keyId" TEXT;
